/**
 * Generate lib/fixtures/hero-match.json — the landing hero's floor.
 *
 *   node --env-file=.env.local scripts/make-hero-fixture.mjs
 *
 * UI-PHASE-2.md §2.4 turns the hero into a query but keeps the fixture,
 * because the reason it existed has not changed: the hero must never fail to
 * render, and free-tier Supabase pauses after about a week idle (this project
 * has recorded pauses of 12 minutes, 12 minutes and 3.3 hours).
 *
 * This runs the same three queries lib/hero-match.ts runs and commits the
 * answer. Doing it here rather than by hand is the point: a hand-written
 * fixture is a claim about the database that nothing checks, and this one has
 * to stay plausible as a real Full Member fixture with real predictions
 * behind it. The capture date travels with it, because a stale hero presented
 * as current is worse than no hero.
 */

import { writeFileSync } from "node:fs";
import { createClient } from "@supabase/supabase-js";

const url = process.env.NEXT_PUBLIC_SUPABASE_URL;
const key = process.env.SUPABASE_SECRET_KEY;
if (!url || !key) {
  console.error("NEXT_PUBLIC_SUPABASE_URL and SUPABASE_SECRET_KEY must be set.");
  console.error("Run with: node --env-file=.env.local scripts/make-hero-fixture.mjs");
  process.exit(1);
}
const supabase = createClient(url, key, { auth: { persistSession: false } });

const teams = await supabase.from("teams").select("team_id, name").eq("full_member", true);
if (teams.error) throw new Error(`teams: ${teams.error.message}`);
const names = new Map(teams.data.map((r) => [r.team_id, r.name]));
console.log(`${names.size} Full Member teams`);

const matches = await supabase
  .from("matches")
  .select("match_id, competition, format, start_time, team_a, team_b, winner, status")
  .in("team_a", [...names.keys()])
  .in("team_b", [...names.keys()])
  .order("start_time", { ascending: false })
  .limit(20);
if (matches.error) throw new Error(`matches: ${matches.error.message}`);

const preds = await supabase
  .from("predictions")
  .select("match_id")
  .in("match_id", matches.data.map((r) => r.match_id))
  .not("innings", "is", null);
if (preds.error) throw new Error(`predictions: ${preds.error.message}`);
const withPredictions = new Set(preds.data.map((r) => r.match_id));

const hit = matches.data.find((r) => withPredictions.has(r.match_id));
if (!hit) {
  console.error(
    `none of the ${matches.data.length} most recent Full Member matches have keyed ` +
      `predictions - refusing to write a fixture that does not match the query it backs`
  );
  process.exit(1);
}

const fixture = {
  _comment:
    "Generated by scripts/make-hero-fixture.mjs. DO NOT HAND-EDIT. Rendered by " +
    "lib/hero-match.ts when the live query fails or finds nothing; the page shows capturedAt.",
  capturedAt: new Date().toISOString().slice(0, 10),
  match: {
    matchId: hit.match_id,
    competition: hit.competition,
    format: hit.format,
    date: hit.start_time ? hit.start_time.slice(0, 10) : null,
    teamA: names.get(hit.team_a),
    teamB: names.get(hit.team_b),
    winner: hit.winner === null ? null : (names.get(hit.winner) ?? null),
    // A committed hero cannot be in progress.
    isLive: false,
  },
};

writeFileSync("lib/fixtures/hero-match.json", JSON.stringify(fixture, null, 2) + "\n");
console.log(
  `hero fixture: ${fixture.match.teamA} v ${fixture.match.teamB}, ` +
    `${fixture.match.date} (${fixture.match.competition}) -> lib/fixtures/hero-match.json`
);
